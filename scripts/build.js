#!/usr/bin/env node
// Builds the Node-RED artefacts from source:
//   dist/ac2-dispatcher-PASTE.js   body of function node ac2.fn.disp
//   dist/ac2-watchdog-PASTE.js     body of function node ac2.fn.watchdog
//   dist/ac2-flow.json             import flow (SHADOW by default: real command outputs UNWIRED; --live wires them)
// Usage: node scripts/build.js [--host daikin1] [--live]   (--live: dry_run off + real command outputs wired)
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const read = (f) => fs.readFileSync(path.join(root, f), 'utf8');

function build(opts) {
  opts = opts || {};
  const cfg = opts.config ? JSON.parse(JSON.stringify(opts.config)) : JSON.parse(read('config/ac2.config.json'));   // opts.config: tests
  delete cfg._comment;
  if (opts.host) cfg.faikout_host = opts.host;
  if (opts.live) cfg.dry_run = false;
  const live = !cfg.dry_run;
  const host = cfg.faikout_host;

  // Hard limits: refuse a config that breaks them outright, raise anything below a floor (and say so).
  const { clampConfig } = require('../src/ac2-limits');
  const checked = clampConfig(cfg);
  if (checked.errors.length && !opts.allowErrors) throw new Error('config/ac2.config.json breaks the hard limits:\n  ' + checked.errors.join('\n  '));
  if (checked.clamped.length && !opts.quiet) console.warn('hard limits raised: ' + checked.clamped.join('; '));

  const stripExports = (src) => src.replace(/\nif \(typeof module[\s\S]*$/, '\n');
  const core = stripExports(read('src/ac2-core.js'));
  const limits = stripExports(read('src/ac2-limits.js'));
  const merge = read('nodered/merge-deep.js');
  const cfgJs = 'const AC2_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n';
  const stamp = (body) => crypto.createHash('sha256').update(body).digest('hex').slice(0, 16);

  const dispBody = cfgJs + '\n' + merge + '\n' + limits + '\n' + core + '\n' + read('nodered/ac2-dispatcher-wrapper.js');
  const wdBody = cfgJs + '\n' + merge + '\n' + limits + '\n' + read('nodered/ac2-watchdog.js');
  const header = (name, body) =>
    '// AC v2 (Faikout) — ' + name + ' — GENERATED by scripts/build.js, do not edit; edit src/ or nodered/ and rebuild.\n' +
    '// sha256[:16] of body below: ' + stamp(body) + '   dry_run: ' + cfg.dry_run + '   host: ' + host + '\n';
  const dispPaste = header('dispatcher ac2.fn.disp', dispBody) + dispBody;
  const wdPaste = header('watchdog ac2.fn.watchdog', wdBody) + wdBody;

  const z = 'ac2.tab', B = 'hwv3.broker';
  const mqttIn = (id, topic, y) => ({ id, type: 'mqtt in', z, name: topic, topic, qos: '0', datatype: 'auto-detect', broker: B, nl: false, rap: true, rh: 0, inputs: 0, x: 170, y, wires: [['ac2.fn.disp']] });
  const mqttOut = (id, name, topic, retain, qos, x, y) => ({ id, type: 'mqtt out', z, name, topic, qos, retain, respTopic: '', contentType: '', userProps: '', correl: '', expiry: '', broker: B, x, y, wires: [] });
  const flow = [
    { id: z, type: 'tab', label: live ? 'AC v2 (Faikout) — LIVE' : 'AC v2 (Faikout) — SHADOW', disabled: false, info: live ? 'Solar-aware Daikin control via Faikout. LIVE: dispatcher + watchdog command the AC on command/' + host + '. Source + docs: this repo (cerbo-solar-aircon).' : 'Solar-aware Daikin control via Faikout. SHADOW: publishes what it WOULD do on bsf/ac2/shadow; real command outputs unwired. Source + docs: this repo (cerbo-solar-aircon).' },
    { id: 'ac2.comment.phase', type: 'comment', z, name: live ? 'LIVE — built from daikin-solar-control (edit there, rebuild, redeploy; do not hand-edit here)' : 'SHADOW — real command outputs (disp out 0, watchdog out 0) are UNWIRED on purpose.', info: '', x: 520, y: 40, wires: [] },
    mqttIn('ac2.in.hw', 'bsf/hotwater/status', 100),
    mqttIn('ac2.in.presence', 'bsf/presence/state', 140),
    mqttIn('ac2.in.acv1', 'bsf/ac/status', 180),
    mqttIn('ac2.in.plugw', 'bsf/ac/plug_power', 220),
    mqttIn('ac2.in.fk_state', 'state/' + host, 260),
    mqttIn('ac2.in.fk_status', 'state/' + host + '/status', 300),
    mqttIn('ac2.in.cmd', 'bsf/ac2/cmd', 340),
    mqttIn('ac2.in.dashcmd', 'bsf/ac/cmd', 380),
    mqttIn('ac2.in.forecast', 'bsf/weather/forecast', 420),
    mqttIn('ac2.in.fk_minute', 'Faikout/' + host, 460),
    mqttIn('ac2.in.arrival', 'bsf/presence/coming_home', 500),
    mqttIn('ac2.in.probe', 'bsf/ac2/probe', 540),
    mqttIn('ac2.in.room_ref', 'bsf/ac2/room_ref', 580),
    { id: 'ac2.inject.tick', type: 'inject', z, name: 'tick 30 s', props: [{ p: 'topic', vt: 'str' }, { p: 'payload' }], repeat: '30', crontab: '', once: true, onceDelay: '5', topic: 'tick', payload: '', payloadType: 'date', x: 170, y: 400, wires: [['ac2.fn.disp']] },
    { id: 'ac2.fn.disp', type: 'function', z, name: 'AC v2 dispatcher', func: dispPaste, outputs: 7, timeout: 0, noerr: 0,
      // On (re)start forget cached inputs (they refill from retained topics within seconds); keep ac2_mem (mode, holds, boost).
      initialize: "flow.set('ac2_in', {});\nflow.set('ac2_last_eval_ms', Date.now());\nflow.set('ac2_start_ms', Date.now());", finalize: '', libs: [], x: 470, y: 240,
      wires: [live ? ['ac2.out.cmd'] : [], ['ac2.out.shadow'], ['ac2.out.status'], ['ac2.out.log'], ['ac2.out.anomaly'], ['ac2.out.poll'], ['ac2.out.manual']] },
    { id: 'ac2.inject.wd', type: 'inject', z, name: 'watchdog 5 min', props: [{ p: 'topic', vt: 'str' }, { p: 'payload' }], repeat: '300', crontab: '', once: true, onceDelay: '60', topic: 'watchdog', payload: '', payloadType: 'date', x: 170, y: 480, wires: [['ac2.fn.watchdog']] },
    { id: 'ac2.fn.watchdog', type: 'function', z, name: 'AC v2 watchdog', func: wdPaste, outputs: 3, timeout: 0, noerr: 0, initialize: '', finalize: '', libs: [], x: 470, y: 480,
      wires: [live ? ['ac2.out.cmd'] : [], ['ac2.out.shadow'], ['ac2.out.anomaly']] },
    mqttOut('ac2.out.shadow', 'bsf/ac2/shadow', 'bsf/ac2/shadow', 'false', '0', 760, 160),
    mqttOut('ac2.out.status', 'bsf/ac2/status', 'bsf/ac2/status', 'true', '0', 760, 200),
    mqttOut('ac2.out.log', 'bsf/ac2/log', 'bsf/ac2/log', 'false', '0', 760, 240),
    mqttOut('ac2.out.anomaly', 'bsf/ac2/anomaly', 'bsf/ac2/anomaly', 'false', '1', 760, 280),
    mqttOut('ac2.out.manual', 'bsf/ac2/manual', 'bsf/ac2/manual', 'false', '1', 760, 360),
    mqttOut('ac2.out.poll', 'Faikout status poll (msg.topic)', '', '', '', 760, 320),
    mqttOut('ac2.out.cmd', live ? 'Faikout command (msg.topic)' : 'Faikout command (msg.topic) — unwired in SHADOW', '', 'false', '1', 760, 400),
  ];
  return { dispPaste, wdPaste, flow, cfg };
}

if (require.main === module) {
  const i = process.argv.indexOf('--host');
  const out = build({ host: i > 0 ? process.argv[i + 1] : undefined, live: process.argv.indexOf('--live') > 0 });
  const dist = path.join(root, 'dist');
  fs.mkdirSync(dist, { recursive: true });
  fs.writeFileSync(path.join(dist, 'ac2-dispatcher-PASTE.js'), out.dispPaste);
  fs.writeFileSync(path.join(dist, 'ac2-watchdog-PASTE.js'), out.wdPaste);
  fs.writeFileSync(path.join(dist, 'ac2-flow.json'), JSON.stringify(out.flow, null, 2) + '\n');
  console.log('built dist/ (host ' + out.cfg.faikout_host + ', dry_run ' + out.cfg.dry_run + ')');
}

module.exports = { build };
